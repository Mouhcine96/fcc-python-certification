# =========================
# Augmented Assignments
# =========================

# Addition
x = 10
x += 5
print(x)  # 15

# Subtraction
y = 14
y -= 3
print(y)  # 11

# Multiplication
z = 5
z *= 4
print(z)  # 20

# Division
price = 100
price /= 4
print(price)  # 25.0

# Floor division
pages = 23
pages //= 5
print(pages)  # 4

# Modulo
bits = 35
bits %= 2
print(bits)  # 1

# Exponentiation
power = 2
power **= 3
print(power)  # 8

# Strings
greet = "Hello"
greet += " World"
print(greet)  # Hello World

greet *= 3
print(greet)  # HelloHelloHello

# No ++ in Python
n = 5
n += 1
print(n)  # 6
