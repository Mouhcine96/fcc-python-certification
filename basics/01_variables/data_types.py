# Common data types

my_integer = 10
my_float = 4.5
my_string = "Hello world"
my_boolean = True
my_list = [22, "Hello", 3.14, True]
my_tuple = (7, 5, 8)
my_set = {7, 5, 8}
my_dict = {"name": "Alice", "age": 25}
my_range = range(5)
my_none = None

print(type(my_integer))
print(type(my_float))
print(type(my_string))
print(type(my_boolean))
print(type(my_list))
print(type(my_tuple))
print(type(my_set))
print(type(my_dict))
print(type(my_range))
print(type(my_none))

# isinstance examples
print(isinstance(my_integer, int))
print(isinstance(my_string, str))
print(isinstance(my_string, int))
